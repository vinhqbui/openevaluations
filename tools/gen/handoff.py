"""Writes datasets/handoff-<family>/ (Harbor tasks, one per task and channel) from frozen A's.

Input: datasets/_shared/handoff/<family>/<task>/, written by `oe freeze` (see tools/oe/handoff.py),
plus the task's spec, hidden test and fix in datasets/_shared/tallyho/. Every channel task builds
the same image: the base tree as one commit with A's workspace.patch applied on top, uncommitted.
Only what is added differs: nothing (repo-only), /handoff/trace.md (trace) or /app/NOTES.md
(notes), and one sentence of the instruction saying where it is.

The leak check runs first and refuses the whole family on a hit: no hidden-test marker may appear
in any frozen artifact. Fix lines refuse a curated (relay) A; in a real interrupted A they are A's
own progress (its image never held the fix), so they are counted in task.toml instead.

Usage: python tools/gen/handoff.py [--check]
"""

import filecmp
import hashlib
import importlib.util
import json
import os
import shutil
import sys
import tempfile
import tomllib
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "tools"))
from oe import handoff  # noqa: E402

TALLYHO = REPO / "datasets" / "_shared" / "tallyho"
SHARED = REPO / "datasets" / "_shared" / "handoff"
FAMILIES = ("interrupt", "relay", *handoff.XVENDOR_FAMILIES)


def _tallyho_gen():
    spec = importlib.util.spec_from_file_location("gen_tallyho", Path(__file__).with_name("tallyho.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


TEST_SH = _tallyho_gen().TEST_SH

