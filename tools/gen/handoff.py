def _toml_list(xs):
    return "[" + ", ".join(f'"{x}"' for x in xs) + "]"


def _w(p, text, exe=False):
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")
    if exe:
        p.chmod(0o755)


def _load_a(d):
    a = json.loads((d / "a.json").read_text(encoding="utf-8"))
    if not a.get("valid"):
        raise SystemExit(f"{d}: frozen A is invalid: {'; '.join(a.get('problems') or [])}")
    for name, digest in a["sha256"].items():
        if hashlib.sha256((d / name).read_bytes()).hexdigest() != digest:
            raise SystemExit(f"{d / name}: sha256 differs from a.json (frozen files are never edited)")
    return a


def _spec(task):
    """A task's spec, hidden test and fix, from the tracker's set or the tallyho-more set."""
    tasks = next(d for d in (TALLYHO / "tasks", TALLYHO / "tasks-more") if (d / f"{task}.toml").exists())
    spec = tomllib.loads((tasks / f"{task}.toml").read_text(encoding="utf-8"))
    (hidden,) = spec["local_tests"]
    return spec, Path(hidden["path"]).name, tasks / hidden["source"], \
        TALLYHO / "fixes" / f"{spec['fix_rev'].removeprefix('fix-')}.patch"


def generate(src=SHARED / "interrupt", out=None, family="interrupt"):
    src = Path(src)
    out = Path(out or REPO / "datasets" / f"handoff-{family}")
    base = handoff.read_tree(TALLYHO / "src")
    plans = []
    for d in sorted(p for p in src.iterdir() if p.is_dir()):
        a = _load_a(d)
        spec, test_name, hidden, fix = _spec(a["task"])
        trace = handoff.render_trace(json.loads((d / "trajectory.json").read_text(encoding="utf-8")))
        artifacts = {"workspace.patch": (d / "workspace.patch").read_text(encoding="utf-8"),
                     "NOTES.md": (d / "NOTES.md").read_text(encoding="utf-8"), "trace.md": trace,
                     "records.json": (d / "records.json").read_text(encoding="utf-8")}
        markers = handoff.leak_markers({test_name: hidden.read_text(encoding="utf-8")},
                                       fix.read_text(encoding="utf-8"), base)
        found = handoff.find_leaks(artifacts, markers)
        stop = [f for f in found if f["kind"] == "hidden_test" or family == "relay"]
        if stop:
            raise SystemExit(f"{d}: leak check failed: " + "; ".join(
                f"{f['kind']} marker {f['marker']!r} in {f['artifact']}" for f in stop[:5]))
        fix_lines = len({f["marker"] for f in found if f["kind"] == "fix"})
        plans.append((d, a, spec, test_name, hidden, fix, trace, fix_lines))

    if out.exists():
        shutil.rmtree(out)
    names = []
    for d, a, spec, test_name, hidden, fix, trace, fix_lines in plans:
        a_sha = hashlib.sha256((d / "a.json").read_bytes()).hexdigest()
        for channel in handoff.family_channels(family):
            name = f"{a['task']}--{channel}"
            t = out / name
            env = t / "environment"
            shutil.copytree(TALLYHO / "src", env / "src")
            shutil.copyfile(d / "workspace.patch", env / "a.patch")
            copy, place, owned = "", "", "/app"
            if channel == "trace":
                _w(env / "handoff" / "trace.md", trace)
                copy, owned = "COPY handoff/ /handoff/\n", "/app /handoff"
            elif channel == "notes":
                (env / "handoff").mkdir()
                shutil.copyfile(d / "NOTES.md", env / "handoff" / "NOTES.md")
                copy ="COPY handoff/ /handoff/\n"
                place = "    && mv /handoff/NOTES.md /app/NOTES.md && rmdir /handoff \\\n"
            elif channel == "records":
                # read by oe_agents.handoff_b before Claude starts, then deleted: B gets them only through av
                (env / "handoff").mkdir()
                shutil.copyfile(d / "records.json", env / "handoff" / "records.json")
                shutil.copyfile(d / "workspace.patch", env / "handoff" / "a.patch")
                copy, owned = "COPY handoff/ /handoff/\n", "/app /handoff"
            _w(env / "Dockerfile", DOCKERFILE.format(copy=copy, place=place, owned=owned))
            _w(t / "instruction.md", f"{LEAD}{WHERE[channel]} Finish the task.\n\n{spec['goal'].strip()}\n")
            _w(t / "task.toml", TASK_TOML.format(
                family=family, task=a["task"], channel=channel, relevant=_toml_list(spec["relevant_files"]),
                max_turns=spec.get("max_turns", 40), a_sha=a_sha, cut_turns=a["cut_turns"], fix_lines=fix_lines))
            (t / "tests").mkdir()
            shutil.copyfile(hidden, t / "tests" / test_name)
            _w(t / "tests" / "test.sh", TEST_SH.format(test=test_name), exe=True)
            (t / "solution").mkdir()
            shutil.copyfile(fix, t / "solution" / "fix.patch")
            _w(t / "solution" / "solve.sh", SOLVE_SH, exe=True)
            names.append(name)
    if names:
        xv = family in handoff.XVENDOR_FAMILIES
        run = (f"PYTHONPATH=agents uv run harbor run -p datasets/handoff-{family} -i '*--records' "
               "-a oe_agents.handoff_b:HandoffBAv ...   # the rest: docs/PREREG-handoff-xvendor.md" if xv else
               f"uv run harbor run -p datasets/handoff-{family} -a claude-code -m anthropic/deepseek-flash -k 8 -o jobs")
        _w(out / "README.md", README.format(family=family, prereg="xvendor" if xv else family, run=run,
                                            tasks="\n".join(f"- `{n}`" for n in names)))
    return names


def _diff(a, b, rel=""):
    cmp = filecmp.dircmp(a, b)
    bad = [rel + x for x in cmp.left_only + cmp.right_only]
    for f in cmp.common_files:
        pa, pb = Path(a) / f, Path(b) / f
        if pa.read_bytes() != pb.read_bytes() or os.access(pa, os.X_OK) != os.access(pb, os.X_OK):
            bad.append(rel + f)
    for sub in cmp.common_dirs:
        bad += _diff(Path(a) / sub, Path(b) / sub, f"{rel}{sub}/")
    return bad


def stale(src, out, family):
    """Paths where `out` differs from what generate(src) writes (empty when up to date)."""
    out = Path(out)
    with tempfile.TemporaryDirectory() as tmp:
        fresh = Path(tmp) / "ds"
        names = generate(src, fresh, family) if Path(src).exists() else []
        if not names:
            return [out.as_posix()] if out.exists() else []
        if not out.exists():
            return [out.as_posix()]
        return _diff(fresh, out)


if __name__ == "__main__":
    check = "--check" in sys.argv
    problems = []
    for fam in FAMILIES:
        src, out = SHARED / fam, REPO / "datasets" / f"handoff-{fam}"
        if check:
            problems += stale(src, out, fam)
        elif src.exists():
            print("\n".join(generate(src, out, fam)))
    if check:
        if problems:
            print("datasets/handoff-* is stale:", problems)
            sys.exit(1)
        print("datasets/handoff-* up to date")
